/**
 * Блок, к которому редактор должен прокрутиться при открытии.
 *
 * Список урока на странице курса ведёт сюда за теми блоками, у которых нет
 * своей страницы правки — за текстом, разметкой, видео, презентацией. Адрес
 * несёт `block=<id>` рядом с уже привычными `courseId` и `moduleId`.
 *
 * Разбор вынесен из страницы по одной причине: его можно проверить тестом, а
 * саму прокрутку — только в браузере.
 */

export function anchoredBlockId(params: URLSearchParams | null): string | null {
  const raw = params?.get("block")?.trim();
  return raw ? raw : null;
}
