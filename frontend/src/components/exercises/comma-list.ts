/**
 * Список через запятую: разбор и сравнение.
 *
 * Живут отдельно от поля, потому что отвечают на вопрос, который проверяется
 * без отрисовки: что означает эта строка и означает ли она то же самое.
 */

/** Что означает набранный текст. Пустые куски и пробелы по краям не в счёт. */
export function parseList(text: string): string[] {
  return text
    .split(",")
    .map((part) => part.trim())
    .filter(Boolean);
}

/**
 * Список чисел.
 *
 * Отдельно от строкового, потому что незаконченное число выглядит иначе:
 * `3.` и `-` — это ещё не числа, но уже и не мусор. `parseFloat` вернёт
 * с них `3` и `NaN`, и поле, пересобранное из разбора, сотрёт точку и минус
 * раньше, чем учитель наберёт остальное. Здесь разбор терпит незаконченное:
 * кусок, который не число, просто не попадает в результат, а на экране
 * остаётся.
 */
export function parseNumberList(text: string): number[] {
  return (
    parseList(text)
      // Пустое отсеивается до преобразования: Number("") — это 0, и пустой
      // кусок после запятой стал бы нулём в задании.
      .map(Number)
      .filter(Number.isFinite)
  );
}

/** Один ли это список. Порядок значим — от него зависит порядок полей ответа. */
export function sameList<T>(a: T[], b: T[]): boolean {
  return a.length === b.length && a.every((item, i) => item === b[i]);
}
